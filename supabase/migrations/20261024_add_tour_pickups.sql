-- 1. Add transfer options and meeting point columns to public.tours table
ALTER TABLE public.tours
  ADD COLUMN IF NOT EXISTS enable_transfer BOOLEAN DEFAULT true,
  ADD COLUMN IF NOT EXISTS meeting_point TEXT DEFAULT 'Ao Nang Pier',
  ADD COLUMN IF NOT EXISTS meeting_time TEXT DEFAULT '08:00',
  ADD COLUMN IF NOT EXISTS additional_notes TEXT DEFAULT 'Please arrive at least 15 minutes before departure time.';

-- 2. Create the tour_pickup_locations table
CREATE TABLE IF NOT EXISTS public.tour_pickup_locations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tour_id BIGINT NOT NULL REFERENCES public.tours(id) ON DELETE CASCADE,
  location_name TEXT NOT NULL,
  adult_price NUMERIC(10, 2) NOT NULL DEFAULT 0,
  child_price NUMERIC(10, 2) NOT NULL DEFAULT 0,
  notes TEXT,
  is_active BOOLEAN NOT NULL DEFAULT true,
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. Create index for performance
CREATE INDEX IF NOT EXISTS idx_tour_pickup_locations_tour_id 
  ON public.tour_pickup_locations(tour_id);

-- 4. Enable Row Level Security (RLS)
ALTER TABLE public.tour_pickup_locations ENABLE ROW LEVEL SECURITY;

-- 5. Set up RLS Policies
-- Allow anyone (public/customers) to view active pick-up locations
DROP POLICY IF EXISTS "Allow public read active pickup locations" ON public.tour_pickup_locations;
CREATE POLICY "Allow public read active pickup locations"
  ON public.tour_pickup_locations
  FOR SELECT
  USING (true);

-- Allow authenticated users / admins to manage (insert, update, delete) pickup locations
DROP POLICY IF EXISTS "Allow admin full access to pickup locations" ON public.tour_pickup_locations;
CREATE POLICY "Allow admin full access to pickup locations"
  ON public.tour_pickup_locations
  FOR ALL
  USING (true)
  WITH CHECK (true);

